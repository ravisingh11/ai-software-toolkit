#!/usr/bin/env python3
"""Shared activation hints and the generated 33-check documentation index.

Catalog and provider contracts own check identities and workflow paths. Hints
supply only configuration and execution guidance; nothing here runs producers.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GUIDE_URL = "https://github.com/ravisingh11/ai-software-toolkit/blob/main/docs/activation.md"
COMMANDS = {
    "build": "PROOF_BUILD_COMMAND", "unit-tests": "PROOF_UNIT_TEST_COMMAND",
    "format-and-lint": "PROOF_FORMAT_LINT_COMMAND",
    "migration-validation": "PROOF_MIGRATION_VALIDATION_COMMAND",
    "changed-code-coverage": "PROOF_CHANGED_COVERAGE_COMMAND",
}
CONFIG_FILES = {
    "documentation-validation": ".proof/documentation.yaml",
    "repository-ground-truth": ".proof/ground-truth-ai.yaml",
    "change-scope": ".proof/change-scope.yaml",
    "pr-metadata": ".proof/pr-metadata.yaml",
}
# Provider-specific hints supplement (never replace) the provider contracts.
PROVIDER_HINTS = {
    "github-codeql": ("PROOF_CODEQL_LANGUAGES", "providers/codeql.md"),
    "github-codeql-default-setup": (None, "providers/codeql.md"),
    "github-dependency-review": ("PROOF_DEPENDENCY_REVIEW_ENABLED", "proof/control-setup.md"),
    "sonarqube": ("SONAR_HOST_URL", "providers/sonarqube.md"),
    "snyk-code": ("SNYK_CODE_ENABLED", "providers/snyk.md"),
    "snyk-open-source": ("SNYK_OPEN_SOURCE_ENABLED", "providers/snyk.md"),
    "fossa": ("FOSSA_ENABLED", "providers/fossa.md"),
    "trivy-repository-vulnerabilities": ("PROOF_TRIVY_DEPENDENCIES_ENABLED", "providers/independent-security.md"),
    "trivy-repository-iac": ("PROOF_TRIVY_IAC_ENABLED", "providers/independent-security.md"),
    "github-artifact-attestations": ("PROOF_ARTIFACT_PROVENANCE_ENABLED", "providers/independent-security.md"),
}


def hints(control: dict, provider_id: str, provider: dict) -> dict:
    """Return declarative setup guidance for one actual provider selection."""
    identifier = control["id"]
    contract = provider.get("checks", {}).get(identifier, {})
    template = provider.get("template") if provider.get("template_available") else None
    workflow = contract.get("workflow_path") or (template.replace("workflows/", ".github/workflows/", 1) if template else None)
    variable, guide = PROVIDER_HINTS.get(provider_id, (None, "proof/control-setup.md"))
    manual = bool(template == "workflows/lifecycle-verification.yml" and provider_id != "github-artifact-attestations")
    if manual:
        guide = "providers/lifecycle.md"
    if provider_id.startswith("ai-"):
        variable, guide = "AI_REVIEW_COMMAND", "proof/control-setup.md"
    prerequisites = [".proof/policy.yaml", ".proof/providers.yaml"]
    if identifier in CONFIG_FILES:
        prerequisites.append(CONFIG_FILES[identifier])
    if workflow:
        prerequisites.append(workflow)
    required_variables = [COMMANDS[identifier]] if identifier in COMMANDS else []
    if variable:
        required_variables.append(variable)
    return {
        "guide": f"{GUIDE_URL}#{identifier}", "details": guide,
        "installed_files": prerequisites, "variables": required_variables,
        "credential_names": provider.get("secrets", []), "workflow": workflow,
        "manual": manual,
        "execution": ("Explicit workflow_dispatch with an owned immutable subject and lifecycle configuration."
                      if manual else "Run the configured provider locally or on its documented CI trigger; inspect the exact-subject result."),
    }


def render_guide(catalog: dict, providers: dict) -> str:
    lines = ["# Activate checks deliberately", "",
             "<!-- Generated by tooling/activation.py; edit shared hints, then regenerate. -->", "",
             "All 33 checks remain optional. Core selects 12 advisory checks; advanced",
             "lifecycle and polyglot execution stay manual. This index describes available",
             "checks, not evidence that they are enabled, executed, or passing.", "",
             "## Five separate steps", "",
             "1. **Install** runtime files and explicitly chosen workflow templates.",
             "2. **Select** a check in `.proof/policy.yaml` for the relevant operation and",
             "   choose its authoritative provider in `.proof/providers.yaml`.",
             "3. **Configure** real commands, provider settings, and prerequisites.",
             "4. **Execute** the appropriate producer locally or in CI. Manual producers",
             "   require an explicit run; a selected check does not start them.",
             "5. **Verify evidence** for the exact revision, PR state, artifact digest, or",
             "   environment the check declares. Configuration and old results are not a pass.", "",
             "Use `ai-toolkit doctor` or `python3 .proof/doctor.py` to inspect setup without",
             "running producers. Command values come from local environment variables or",
             "GitHub repository variables. Secret values stay in the provider platform or",
             "the trusted `proof-providers` environment. Fork credentials remain withheld.", "",
             "## Enable, verify, enforce, or disable", "",
             "For every row below, use `.proof/configure.py --list` and the",
             "[setup guide](proof/control-setup.md) to review policy and provider changes.",
             "The provider column lists the default selection and all alternatives; changing",
             "providers alone does not select a previously inactive check.", "",
             "Inspect the producer run and [evidence contract](proof/producer-contract.md),",
             "then the scorecard's subject, authoritative provider, status, and evidence link.",
             "Missing credentials, stale results, blocked execution, and producers never run",
             "remain unverified. Only selected applicable checks affect evaluation scores.", "",
             "**Enforcement is a separate explicit decision.** Keep advisory mode until the",
             "producer, stable check name, failure behavior, and exact-subject evidence are",
             "verified. AI review and functional QA remain advisory-only. GitHub branch",
             "protection is configured separately and is never changed by installation or doctor.", "",
             "**Disable** by setting the operation's override to `not_activated` and disabling",
             "the provider's trigger/enable variable separately. Deselecting does not stop a",
             "workflow; removing a workflow does not deselect a check. Review owned required",
             "merge checks separately so a disabled producer cannot leave merges waiting.", "",
             "## All 33 checks", ""]
    for control in catalog["controls"]:
        identifier = control["id"]
        selected = providers["selections"][identifier]["authoritative"]
        provider = providers["providers"][selected]
        hint = hints(control, selected, provider)
        alternatives = [pid for pid, value in providers["providers"].items() if identifier in value.get("capabilities", []) and pid != selected]
        lines.extend([f"### {identifier}", "", f"**{control['name']}** — {control['purpose']}.", "",
                      f"- Stage / evidence subject: `{control['stage']}` / `{control['evidence_subject']}`.",
                      f"- Provider selection: `{selected}`" + ("; alternatives: " + ", ".join(f"`{pid}`" for pid in alternatives) if alternatives else "") + ".",
                      "- Installed prerequisites: " + ", ".join(f"`{path}`" for path in hint["installed_files"]) + ".",
                      "- Configuration / enablement: " + (", ".join(f"`{key}`" for key in hint["variables"]) if hint["variables"] else "repository-owned configuration and provider prerequisites") +
                      ("; secret names: " + ", ".join(f"`{key}`" for key in hint["credential_names"]) if hint["credential_names"] else "; no provider secret declared") + ".",
                      f"- Execution: {hint['execution']}",
                      f"- Verification: require authoritative evidence for the exact `{control['evidence_subject']}`; see the common verification, enforcement, and disabling steps above.",
                      f"- Practical guide: [setup and limits]({hint['details']}).", ""])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write-guide", action="store_true")
    args = parser.parse_args()
    guide = render_guide(json.loads((ROOT / "policies/control-catalog.yaml").read_text()),
                         json.loads((ROOT / "policies/provider-config.yaml").read_text()))
    if args.write_guide:
        (ROOT / "docs/activation.md").write_text(guide, encoding="utf-8")
    else:
        print(guide, end="")


if __name__ == "__main__":
    main()
